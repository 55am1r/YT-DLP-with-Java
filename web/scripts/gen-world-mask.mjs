// Builds src/admin/worldMaskData.js — the land/sea grid behind the admin panel's ASCII map.
//
// Input: Natural Earth 1:50m land (public domain) as TopoJSON, from the world-atlas package.
// It is not a dependency of the app; fetch it just for this run:
//
//   npm install --no-save world-atlas@2
//   node scripts/gen-world-mask.mjs node_modules/world-atlas/land-50m.json
//
// Output: a 720 × 360 grid (0.5° cells, rows from 90°N southwards). Each row is stored as
// run lengths in base 36 joined by '.', alternating sea and land, starting with sea — about
// 20 KB instead of the 2 MB source.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const W = 720
const H = 360
const RES = 180 / H

const input = process.argv[2]
if (!input) {
  console.error('usage: node scripts/gen-world-mask.mjs <path to land-50m.json>')
  process.exit(2)
}
const topo = JSON.parse(readFileSync(input, 'utf8'))

// --- TopoJSON → rings of [lon, lat] (quantized, delta-encoded arcs) ---
const { scale = [1, 1], translate = [0, 0] } = topo.transform || {}
const arcs = topo.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    if (topo.transform) {
      x += dx
      y += dy
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
    }
    return [dx, dy]
  })
})
const ringOf = (indexes) => {
  const pts = []
  for (const i of indexes) {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i]
    arc.forEach((p, k) => { if (k > 0 || pts.length === 0) pts.push(p) })
  }
  return pts
}
const rings = []
const addGeometry = (g) => {
  if (g.type === 'GeometryCollection') g.geometries.forEach(addGeometry)
  else if (g.type === 'Polygon') g.arcs.forEach((r) => rings.push(ringOf(r)))
  else if (g.type === 'MultiPolygon') g.arcs.forEach((poly) => poly.forEach((r) => rings.push(ringOf(r))))
}
addGeometry(topo.objects.land)

// An edge jumping across the antimeridian would smear a fill across the whole row.
let wraps = 0
for (const ring of rings) {
  for (let k = 0; k + 1 < ring.length; k++) if (Math.abs(ring[k + 1][0] - ring[k][0]) > 180) wraps++
}

// --- even-odd scanline fill at each row's centre latitude ---
const mask = new Uint8Array(W * H)
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) * RES
  const xs = []
  for (const ring of rings) {
    for (let k = 0; k + 1 < ring.length; k++) {
      const [x1, y1] = ring[k]
      const [x2, y2] = ring[k + 1]
      if (Math.abs(x2 - x1) > 180) continue
      if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
        xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1))
      }
    }
  }
  xs.sort((a, b) => a - b)
  for (let i = 0; i + 1 < xs.length; i += 2) {
    const c0 = Math.max(0, Math.ceil((xs[i] + 180) / RES - 0.5))
    const c1 = Math.min(W - 1, Math.floor((xs[i + 1] + 180) / RES - 0.5))
    for (let c = c0; c <= c1; c++) mask[r * W + c] = 1
  }
}

// --- run-length encode ---
const rows = []
for (let r = 0; r < H; r++) {
  const runs = []
  let land = 0
  let run = 0
  for (let c = 0; c < W; c++) {
    if (mask[r * W + c] === land) run++
    else {
      runs.push(run)
      land ^= 1
      run = 1
    }
  }
  runs.push(run)
  rows.push(runs.map((n) => n.toString(36)).join('.'))
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'admin', 'worldMaskData.js')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `// Generated by scripts/gen-world-mask.mjs from Natural Earth 1:50m land (public domain,
// naturalearthdata.com) — do not edit by hand. ${W} × ${H} cells of ${RES}°, rows from 90°N
// southwards; each row is base-36 run lengths joined by '.', alternating sea and land,
// starting with sea.
export const MASK = {
  w: ${W},
  h: ${H},
  rows: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
}
`)
const landShare = mask.reduce((a, b) => a + b, 0) / mask.length
console.log(`rings ${rings.length}, antimeridian edges skipped ${wraps}, land ${(landShare * 100).toFixed(1)}% → ${out}`)
